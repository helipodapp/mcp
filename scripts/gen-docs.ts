// scripts/gen-docs.ts — write the MCP tool reference page for docs.helipod.io from the tool definitions.
//   bun scripts/gen-docs.ts [out.mdx]   (default: ../docs-helipod/content/docs/helipod/mcp-tools.mdx)
import { z } from "zod";
import { containerTools } from "../src/tools/containers.js";
import { vpsTools } from "../src/tools/vps.js";
import { domainTools } from "../src/tools/domains.js";
import { emailTools } from "../src/tools/email.js";
import { generalTools } from "../src/tools/general.js";
import type { ToolDef } from "../src/tool.js";

const out = process.argv[2] ?? new URL("../../docs-helipod/content/docs/helipod/mcp-tools.mdx", import.meta.url).pathname;

const GROUPS: [string, string, ToolDef<any>[]][] = [
    ["Containers", "Container API key scope. Projects, services, deployments, variables, domains, scaling, volumes, logs, templates.", containerTools],
    ["VPS", "VPS API key scope.", vpsTools],
    ["Domains", "Domain API key scope (a whole-account key). `search_domain` and `domain_prices` need no key.", domainTools],
    ["Email", "Uses the email API key (`HELIPOD_EMAIL_API_KEY`).", emailTools],
    ["Other", "", generalTools],
];
const KIND = { read: "read-only", write: "write", destructive: "destructive" } as const;

/** One-line type of a JSON Schema property. */
function typeOf(p: any): string {
    if (!p) return "any";
    if (p.enum) return p.enum.map((v: unknown) => JSON.stringify(v)).join(" | ");
    if (p.anyOf) return p.anyOf.map(typeOf).join(" | ");
    if (p.type === "array") return `${typeOf(p.items)}[]`;
    if (p.type === "object") return "object";
    return Array.isArray(p.type) ? p.type.join(" | ") : String(p.type ?? "any");
}
const cell = (v: unknown) => String(v ?? "").replace(/\|/g, "\\|").replace(/\n+/g, " ").replace(/[{}<>]/g, (c) => `\\${c}`);

let mdx = `---
title: MCP tool reference
description: Every tool of the Helipod MCP server, with its parameters and whether it reads, writes or destroys.
icon: Wrench
---

{/* Generated by helipod-mcp/scripts/gen-docs.ts from the tool definitions. Do not edit by hand. */}

The [Helipod MCP server](/docs/helipod/ai-agents) has ${GROUPS.reduce((n, g) => n + g[2].length, 0)} tools. Each one calls the public API with your key, so it can only do what that key allows.

- **read-only** tools never change anything.
- **write** tools create or change something. Tools marked *costs money* charge your Helipod wallet; the server tells the agent to show the price and wait for your OK first.
- **destructive** tools delete or overwrite. Clients that support MCP tool hints ask before running them.

Errors come back as \`{ status, code, error }\` with the same codes as the API, see [Requests and errors](/docs/helipod/requests-and-errors).
`;

for (const [title, note, tools] of GROUPS) {
    mdx += `\n## ${title}\n\n${note ? `${note}\n\n` : ""}`;
    for (const t of tools) {
        const schema: any = z.toJSONSchema(z.object(t.input));
        const props = Object.entries<any>(schema.properties ?? {});
        const required = new Set<string>(schema.required ?? []);
        const costs = /COSTS MONEY/i.test(t.description);
        mdx += `### \`${t.name}\`\n\n**${t.title}** · ${KIND[t.kind as keyof typeof KIND]}${costs ? " · costs money" : ""}\n\n${cell(t.description)}\n\n`;
        if (props.length) {
            mdx += "| Parameter | Type | Required | Description |\n|---|---|---|---|\n";
            for (const [name, p] of props) mdx += `| \`${name}\` | ${cell(typeOf(p))} | ${required.has(name) ? "yes" : ""} | ${cell(p.description ?? "")} |\n`;
            mdx += "\n";
        } else mdx += "No parameters.\n\n";
    }
}

await Bun.write(out, mdx);
console.log(`wrote ${out} (${GROUPS.reduce((n, g) => n + g[2].length, 0)} tools)`);
